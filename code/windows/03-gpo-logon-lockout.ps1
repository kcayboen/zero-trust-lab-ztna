                      instructor placed in GG-ZTNA-Admins becomes an explicit
                      exception exactly as the manuscript requires.

.PARAMETER PushFirewallRules
    Also (re)create the host firewall rules on the lab machines over WinRM.
    Off by default: the package is draft-only and must not touch the live lab.

.EXAMPLE
    PS> .\03-gpo-logon-lockout.ps1

.EXAMPLE
    PS> .\03-gpo-logon-lockout.ps1 -PushFirewallRules -LabHosts Student1,Student2,Instructor1

