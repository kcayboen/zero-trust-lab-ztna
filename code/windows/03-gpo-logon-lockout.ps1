    }
    foreach ($id in $fwRules.Keys) {
        Set-GpoRegistryValue -GpoName $wsGpo -Key $fwRuleKey -ValueName $id -Type String -Value $fwRules[$id]
    }
    # 'StandardProfile' is the legacy name of the Private profile; PublicProfile
    # must be listed explicitly or a NIC that falls back to Public keeps the
    # built-in local 'Any' rules.
    $fwProfiles = @('DomainProfile', 'PrivateProfile', 'PublicProfile')
    foreach ($profile in $fwProfiles) {
        $fwKey = "HKLM\SOFTWARE\Policies\Microsoft\WindowsFirewall\$profile"
        Set-GpoRegistryValue -GpoName $wsGpo -Key $fwKey -ValueName 'EnableFirewall' -Type DWord -Value 1
        Set-GpoRegistryValue -GpoName $wsGpo -Key $fwKey -ValueName 'DefaultInboundAction' -Type DWord -Value 1
        Set-GpoRegistryValue -GpoName $wsGpo -Key $fwKey -ValueName 'DefaultOutboundAction' -Type DWord -Value 0
        Set-GpoRegistryValue -GpoName $wsGpo -Key $fwKey -ValueName 'AllowLocalPolicyMerge' -Type DWord -Value 0
        # Firewall logging is read only from the profile's 'Logging' subkey. Until 2026-11-14 the two
        # values below were written to the profile key itself and silently ignored (no pfirewall.log);
        # found while preparing the S5 same-VLAN measurement. Remove the misplaced copies.
        foreach ($stale in 'LogDroppedPackets', 'LogFileSize') {
            Remove-GPRegistryValue -Name $wsGpo -Key $fwKey -ValueName $stale -ErrorAction SilentlyContinue | Out-Null
        }
        $logKey = "$fwKey\Logging"
        Set-GpoRegistryValue -GpoName $wsGpo -Key $logKey -ValueName 'LogDroppedPackets' -Type DWord -Value 1
        Set-GpoRegistryValue -GpoName $wsGpo -Key $logKey -ValueName 'LogSuccessfulConnections' -Type DWord -Value 0
        Set-GpoRegistryValue -GpoName $wsGpo -Key $logKey -ValueName 'LogFileSize' -Type DWord -Value 16384
        Set-GpoRegistryValue -GpoName $wsGpo -Key $logKey -ValueName 'LogFilePath' -Type ExpandString -Value '%systemroot%\system32\LogFiles\Firewall\pfirewall.log'
    }
    Update-GpoVersion -GpoId (Get-GPO -Name $wsGpo).Id

    # =======================================================================
    # GPO 4 - Logon rights on student workstations
    #        allow: students (any student WS) + instructors + admins
    #        RDP  : administrators only (students must not remote in)
    # =======================================================================
    $studentLogonGpo = 'D202-Logon-StudentWS'
    $null = Get-GpoOrCreate -Name $studentLogonGpo
    Add-GpoLinkIfMissing -Name $studentLogonGpo -Target "OU=Workstations,$d202DN" -Order 1

    $allowWs = @(
        $sidLocalAdmins, $sidDomainAdmins, $sidEnterpriseAdmins, $sidAdmins, $sidStudents, $sidInstructors
    ) | Where-Object { $_ } | ForEach-Object { '*' + $_ }
    $rdpWs = @($sidLocalAdmins, $sidDomainAdmins, $sidEnterpriseAdmins, $sidAdmins) |
        Where-Object { $_ } | ForEach-Object { '*' + $_ }

    Set-GpoSecurityTemplate -GpoName $studentLogonGpo -PrivilegeRights @(
        ('SeInteractiveLogonRight = ' + ($allowWs -join ','))
        ('SeRemoteInteractiveLogonRight = ' + ($rdpWs -join ','))
        ('SeDenyInteractiveLogonRight = *' + $sidGuests)
        ('SeDenyRemoteInteractiveLogonRight = *' + $sidGuests)
    ) -BumpVersion

    # =======================================================================
    # GPO 5 - Deny students on the instructor workstation
    #        Filtered (security filtering) to the Instructor1 computer object,
    #        so the fixed OU structure can be kept. Deny overrides allow.
    # =======================================================================
    $instructorWsGpo = 'D202-Logon-InstructorWS'
    $null = Get-GpoOrCreate -Name $instructorWsGpo
    # Instructor1 is pre-staged in its own OU (02-ous-users-groups.ps1), so the
    # GPO is scoped by link instead of by per-object security filtering. This
    # avoids Set-GPPermission, which blocks on SYSVOL ACL propagation.
    Add-GpoLinkIfMissing -Name $instructorWsGpo -Target "OU=InstructorWorkstations,$d202DN" -Order 1

    $allowInstructorWs = @($sidLocalAdmins, $sidDomainAdmins, $sidEnterpriseAdmins, $sidAdmins, $sidInstructors) |
        Where-Object { $_ } | ForEach-Object { '*' + $_ }
    Set-GpoSecurityTemplate -GpoName $instructorWsGpo -PrivilegeRights @(
        ('SeInteractiveLogonRight = ' + ($allowInstructorWs -join ','))
        ('SeRemoteInteractiveLogonRight = ' + ($rdpWs -join ','))
        ('SeDenyInteractiveLogonRight = *' + $sidStudents + ',*' + $sidGuests)
        ('SeDenyRemoteInteractiveLogonRight = *' + $sidStudents + ',*' + $sidGuests)
    ) -BumpVersion

    Write-Step 'Scope: D202-Logon-InstructorWS linked to OU=InstructorWorkstations only' OK

    # =======================================================================
    # GPO 6 - Server logon rights (D202/Servers + Domain Controllers)
    #        Allow-list only: Administrators / Domain Admins / GG-ZTNA-Admins.
    #        Instructors (GG-Instructors) are absent -> denied; adding an
    #        instructor to GG-ZTNA-Admins makes them an explicit exception.
    # =======================================================================
    $serverGpo = 'D202-Logon-Server'
    $null = Get-GpoOrCreate -Name $serverGpo
    Add-GpoLinkIfMissing -Name $serverGpo -Target "OU=Servers,$d202DN" -Order 1
    Add-GpoLinkIfMissing -Name $serverGpo -Target "OU=Domain Controllers,$domainDN" -Order 1

    $allowServer = @($sidLocalAdmins, $sidDomainAdmins, $sidEnterpriseAdmins, $sidAdmins) |
        Where-Object { $_ } | ForEach-Object { '*' + $_ }

    Set-GpoSecurityTemplate -GpoName $serverGpo -PrivilegeRights @(
        ('SeInteractiveLogonRight = ' + ($allowServer -join ','))
        ('SeRemoteInteractiveLogonRight = ' + ($allowServer -join ','))
        ('SeDenyInteractiveLogonRight = *' + $sidStudents)
        ('SeDenyRemoteInteractiveLogonRight = *' + $sidStudents)
        ('SeDenyNetworkLogonRight = *' + $sidGuests)
    ) -BumpVersion

    # =======================================================================
    # GPO 7 - Device validation support: the workstation must be domain joined
    #        and the logon must come from the console, so cached/offline logons
    #        and unregistered devices cannot be used to bypass the PDP.
    # =======================================================================
    $deviceGpo = 'D202-DeviceValidation'
    $null = Get-GpoOrCreate -Name $deviceGpo
    Add-GpoLinkIfMissing -Name $deviceGpo -Target "OU=Workstations,$d202DN" -Order 3
    Add-GpoLinkIfMissing -Name $deviceGpo -Target "OU=InstructorWorkstations,$d202DN" -Order 3
    Set-GpoRegistryValue -GpoName $deviceGpo -Key 'HKLM\SOFTWARE\Microsoft\Windows\CurrentVersion\Policies\System' `
        -ValueName 'DisableAutomaticRestartSignOn' -Type DWord -Value 0
    Set-GpoRegistryValue -GpoName $deviceGpo -Key 'HKLM\SOFTWARE\Policies\Microsoft\Windows\System' `
        -ValueName 'AllowDomainPINLogon' -Type DWord -Value 0
    # Cached credential count 0 forces every console logon to reach a DC, which
    # is what makes the authentication-latency measurement end-to-end.
    Set-GpoSecurityTemplate -GpoName $deviceGpo -RegistryValues @(
        'MACHINE\Software\Microsoft\Windows NT\CurrentVersion\Winlogon\CachedLogonsCount=1,"0"'
        'MACHINE\Software\Microsoft\Windows NT\CurrentVersion\Winlogon\ForceUnlockLogon=4,1'
    ) -BumpVersion

    # =======================================================================
    # Optional - host firewall rules on the lab machines (WinRM push)
    # =======================================================================
    if ($PushFirewallRules) {
        $ruleScript = {
            param([string]$Role)

            function Ensure-Rule {
                param([string]$DisplayName, [hashtable]$Spec)
                $existing = Get-NetFirewallRule -DisplayName $DisplayName -ErrorAction SilentlyContinue
                if ($existing) {
                    Set-NetFirewallRule -DisplayName $DisplayName -Enabled True -Action $Spec.Action -ErrorAction SilentlyContinue
                    return
                }
                New-NetFirewallRule -DisplayName $DisplayName @Spec -ErrorAction Stop | Out-Null
            }

            # Windows Event Forwarding / WinRM from the collector only.
            Ensure-Rule -DisplayName 'ZTNA-WEF-WinRM-In' -Spec @{
                Direction = 'Inbound'; Protocol = 'TCP'; LocalPort = 5985
                RemoteAddress = '10.20.30.10'; Action = 'Allow'; Profile = 'Domain'
                Description = 'ZTNA test bed: WEF forwarder traffic from DC01 only'
            }
            # Remote administration for the explicit admin subnet.
            Ensure-Rule -DisplayName 'ZTNA-RDP-Admins-In' -Spec @{
                Direction = 'Inbound'; Protocol = 'TCP'; LocalPort = 3389
                RemoteAddress = '10.20.30.0/24'; Action = 'Allow'; Profile = 'Domain'
                Description = 'ZTNA test bed: RDP from the server VLAN only'
            }
            Ensure-Rule -DisplayName 'ZTNA-ICMP-Lab-In' -Spec @{
                Direction = 'Inbound'; Protocol = 'ICMPv4'
                RemoteAddress = '10.20.0.0/16'; Action = 'Allow'; Profile = 'Domain'
                Description = 'ZTNA test bed: reachability testing between lab VLANs'
            }
            if ($Role -eq 'Server') {
                Ensure-Rule -DisplayName 'ZTNA-DNS-Lab-In' -Spec @{
                    Direction = 'Inbound'; Protocol = 'UDP'; LocalPort = 53
                    RemoteAddress = '10.20.0.0/16'; Action = 'Allow'; Profile = 'Domain'
                    Description = 'ZTNA test bed: DNS for lab clients'
                }
                Ensure-Rule -DisplayName 'ZTNA-Kerberos-Lab-In' -Spec @{
                    Direction = 'Inbound'; Protocol = 'TCP'; LocalPort = '88,389,464'
                    RemoteAddress = '10.20.0.0/16'; Action = 'Allow'; Profile = 'Domain'
                    Description = 'ZTNA test bed: Kerberos/LDAP for domain authentication'
                }
            }
            Get-NetFirewallRule -DisplayName 'ZTNA-*' | Select-Object DisplayName, Enabled, Direction, Action
        }

        $targets = if ($PushFirewallRules) { @('DC01') + $LabHosts } else { @() }
        foreach ($target in $targets) {
            $role = if ($target -eq 'DC01') { 'Server' } else { 'Workstation' }
            Write-Step "Pushing firewall baseline to $target ($role)"
            $invokeParams = @{
                ComputerName = $target
                ScriptBlock  = $ruleScript
                ArgumentList = $role
                ErrorAction  = 'Stop'
            }
            if ($LabCredential) { $invokeParams['Credential'] = $LabCredential }
            try {
                Invoke-Command @invokeParams | Format-Table -AutoSize | Out-String | Write-Host
                Write-Step "Firewall baseline applied on $target" OK
            } catch {
                Write-Step ("Firewall push to {0} failed: {1}" -f $target, $_.Exception.Message) WARN
            }
        }
    }

    # =======================================================================
    # Force policy refresh on the DC so verification sees the new state
    # =======================================================================
    & gpupdate.exe /force /target:computer 2>&1 | Out-Null
    Write-Step 'gpupdate /force executed on DC01' OK

    Get-GPO -All | Where-Object { $_.DisplayName -like 'D202-*' } |
        Select-Object DisplayName, Id, GpoStatus, ModificationTime | Format-Table -AutoSize

    Write-Step 'STAGE COMPLETE. Next: 04-wef-collector.ps1' OK
}
catch {
    Write-Step ("FAILED: {0}" -f $_.Exception.Message) ERROR
    Write-Step ($_.ScriptStackTrace) ERROR
    $exitCode = 1
}
finally {
    try { Stop-Transcript | Out-Null } catch { }
}

exit $exitCode
