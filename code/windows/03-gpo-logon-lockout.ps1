function Get-GpoOrCreate {
    param([string]$Name)
    $gpo = Get-GPO -Name $Name -ErrorAction SilentlyContinue
    if (-not $gpo) {
        if (-not $PSCmdlet.ShouldProcess($Name, 'Create GPO')) { return $null }
        $gpo = New-GPO -Name $Name -Comment 'D202 ZTNA test bed - generated by 03-gpo-logon-lockout.ps1' -ErrorAction Stop
        Write-Step "Created GPO $Name" OK
    } else {
        Write-Step "GPO exists: $Name" OK
    }
    return $gpo
}

function Add-GpoLinkIfMissing {
    param([string]$Name, [string]$Target, [int]$Order = 1)
    $inheritance = Get-GPInheritance -Target $Target -ErrorAction Stop
    $already = $inheritance.GpoLinks | Where-Object { $_.DisplayName -eq $Name }
    if ($already) {
        Write-Step "GPO $Name already linked to $Target" OK
        return
    }
    if (-not $PSCmdlet.ShouldProcess($Target, "Link GPO $Name")) { return }
    # Link order cannot exceed (current link count + 1); an OU with no links only
    # accepts order 1. Clamp instead of failing on an empty container.
    $maxOrder = @($inheritance.GpoLinks).Count + 1
    if ($Order -gt $maxOrder) { $Order = $maxOrder }
    New-GPLink -Name $Name -Target $Target -LinkEnabled Yes -Order $Order -ErrorAction Stop | Out-Null
    Write-Step "Linked $Name -> $Target (order $Order)" OK
}

function Set-GpoRegistryValue {
    param(
        [string]$GpoName,
        [string]$Key,
        [string]$ValueName,
        [ValidateSet('DWord', 'String', 'ExpandString', 'QWord', 'MultiString')]
        [string]$Type = 'DWord',
        [object]$Value = 1
    )
    try {
        Set-GPRegistryValue -Name $GpoName -Key $Key -ValueName $ValueName -Type $Type -Value $Value -ErrorAction Stop | Out-Null
    } catch {
        # A pre-existing value with another type makes Set-GPRegistryValue fail;
        # remove and recreate so re-runs converge instead of aborting.
        try {
            Remove-GPRegistryValue -Name $GpoName -Key $Key -ValueName $ValueName -ErrorAction SilentlyContinue | Out-Null
            Set-GPRegistryValue -Name $GpoName -Key $Key -ValueName $ValueName -Type $Type -Value $Value -ErrorAction Stop | Out-Null
        } catch {
            Write-Step ("Registry value failed: {0}\{1} :: {2}" -f $Key, $ValueName, $_.Exception.Message) WARN
        }
    }
}

function Get-GpoSysvolPath {
    param([guid]$GpoId)
    $dnsRoot = (Get-ADDomain).DNSRoot
    $path = '\\{0}\SYSVOL\{0}\Policies\{{{1}}}' -f $dnsRoot, $GpoId
    if (-not (Test-Path -LiteralPath $path)) {
        # SYSVOL replication can lag right after GPO creation.
        for ($i = 0; $i -lt 12; $i++) {
            Start-Sleep -Seconds 5
            if (Test-Path -LiteralPath $path) { break }
        }
    }
    if (-not (Test-Path -LiteralPath $path)) { throw "SYSVOL path not available: $path" }
    return $path
}

function Add-GpoCseExtension {
    param([guid]$GpoId, [string]$Extension = $script:SecurityCse)
    $domainDN = (Get-ADDomain).DistinguishedName
    $gpoPath = "LDAP://CN={$GpoId},CN=Policies,CN=System,$domainDN"
    $entry = [ADSI]$gpoPath
    $current = ''
    try { $current = [string]$entry.Properties['gPCMachineExtensionNames'].Value } catch { }
    # The CSE GUID list contains '[' and '{' which are wildcard metacharacters
    # for -like, so a literal substring test is used instead.
    if ($current.IndexOf($Extension, [StringComparison]::OrdinalIgnoreCase) -lt 0) {
        $entry.Properties['gPCMachineExtensionNames'].Value = $current + $Extension
        $entry.CommitChanges()
        Write-Step "Added CSE extension $Extension to GPO {$GpoId}" OK
    }
}

function Update-GpoVersion {
    param([guid]$GpoId)
    $domainDN = (Get-ADDomain).DistinguishedName
    $gpoPath = "LDAP://CN={$GpoId},CN=Policies,CN=System,$domainDN"
    $entry = [ADSI]$gpoPath
    $current = [int64]$entry.Properties['versionNumber'].Value
    # High 16 bits = USER version, low 16 bits = COMPUTER version. Everything
    # this script writes is computer configuration, so bump the low word; a
    # computer version of 0 makes clients skip the GPO as "Not Applied (Empty)".
    $newVersion = $current + 1
    $entry.Properties['versionNumber'].Value = [int]$newVersion
    $entry.CommitChanges()

    $sysvol = Get-GpoSysvolPath -GpoId $GpoId
    $iniPath = Join-Path $sysvol 'GPT.INI'
    if (Test-Path -LiteralPath $iniPath) {
        $lines = Get-Content -LiteralPath $iniPath
        $lines = $lines | ForEach-Object { if ($_ -match '^Version=') { "Version=$newVersion" } else { $_ } }
        Set-Content -LiteralPath $iniPath -Value $lines -Encoding ASCII
    }
    Write-Step "GPO {$GpoId} version -> $newVersion" OK
}

function Set-GpoSecurityTemplate {
    <#
        Writes GptTmpl.inf (secedit security template) into the GPO. Sections are
        passed as raw INF lines so each GPO documents exactly what it changes.
    #>
    param(
        [string]$GpoName,
        [string[]]$PrivilegeRights = @(),
        [string[]]$SystemAccess = @(),
        [string[]]$RegistryValues = @(),
        [switch]$BumpVersion
    )
    $gpo = Get-GPO -Name $GpoName -ErrorAction Stop
    $sysvol = Get-GpoSysvolPath -GpoId $gpo.Id
    $seceditDir = Join-Path $sysvol 'Machine\microsoft\windows nt\SecEdit'
    if (-not (Test-Path -LiteralPath $seceditDir)) {
        New-Item -ItemType Directory -Path $seceditDir -Force | Out-Null
    }

    $inf = New-Object System.Collections.Generic.List[string]
    $inf.Add('[Unicode]')
    $inf.Add('Unicode=yes')
    $inf.Add('[Version]')
    $inf.Add('signature="$CHICAGO$"')
    $inf.Add('Revision=1')
    if ($SystemAccess.Count -gt 0) {
        $inf.Add('[System Access]')
        foreach ($line in $SystemAccess) { $inf.Add($line) }
    }
    if ($PrivilegeRights.Count -gt 0) {
        $inf.Add('[Privilege Rights]')
        foreach ($line in $PrivilegeRights) { $inf.Add($line) }
    }
    if ($RegistryValues.Count -gt 0) {
        $inf.Add('[Registry Values]')
        foreach ($line in $RegistryValues) { $inf.Add($line) }
    }

    $infPath = Join-Path $seceditDir 'GptTmpl.inf'
    # secedit requires Unicode (UTF-16LE) for the template.
    Set-Content -LiteralPath $infPath -Value $inf -Encoding Unicode
    Write-Step "Security template written: $infPath" OK

    Add-GpoCseExtension -GpoId $gpo.Id
    if ($BumpVersion) { Update-GpoVersion -GpoId $gpo.Id }
}

function Set-GpoAuditPolicy {
    param([string]$GpoName, [object[]]$Subcategories)
    $gpo = Get-GPO -Name $GpoName -ErrorAction Stop
    $sysvol = Get-GpoSysvolPath -GpoId $gpo.Id
    $auditDir = Join-Path $sysvol 'Machine\microsoft\windows nt\Audit'
    if (-not (Test-Path -LiteralPath $auditDir)) {
        New-Item -ItemType Directory -Path $auditDir -Force | Out-Null
    }
    $csvPath = Join-Path $auditDir 'audit.csv'
    $rows = New-Object System.Collections.Generic.List[string]
    $rows.Add('Machine Name,Policy Target,Subcategory,Subcategory GUID,Inclusion Setting,Exclusion Setting,Setting Value')
    foreach ($item in $Subcategories) {
        $rows.Add(('{0},System,{1},{2},{3},,{4}' -f '', $item.Name, $item.Guid, $item.Inclusion, $item.Value))
    }
    Set-Content -LiteralPath $csvPath -Value $rows -Encoding ASCII

    # Force subcategory settings to win over legacy category settings.
    Set-GpoRegistryValue -GpoName $GpoName -Key 'HKLM\SYSTEM\CurrentControlSet\Control\Lsa' `
        -ValueName 'SCENoApplyLegacyAuditPolicy' -Type DWord -Value 1

    Add-GpoCseExtension -GpoId $gpo.Id -Extension $script:AuditCse
    # The Security CSE must NOT be advertised without a GptTmpl.inf: clients
    # then fail with SceCli 1001 ("Cannot access the template", error 2) and
    # abort security-policy propagation for EVERY GPO (user rights, lockout,
    # cached logons). Strip it if an earlier run of this script added it.
    $infPath = Join-Path $sysvol 'Machine\Microsoft\Windows NT\SecEdit\GptTmpl.inf'
    if (-not (Test-Path -LiteralPath $infPath)) {
        $entry = [ADSI]"LDAP://CN={$($gpo.Id)},CN=Policies,CN=System,$((Get-ADDomain).DistinguishedName)"
        $current = [string]$entry.Properties['gPCMachineExtensionNames'].Value
        $i = $current.IndexOf($script:SecurityCse, [StringComparison]::OrdinalIgnoreCase)
        if ($i -ge 0) {
            $entry.Properties['gPCMachineExtensionNames'].Value = $current.Remove($i, $script:SecurityCse.Length)
            $entry.CommitChanges()
            Write-Step "Removed Security CSE from $GpoName (no GptTmpl.inf)" OK
        }
    }
    Write-Step "Advanced audit policy written: $csvPath ($($Subcategories.Count) subcategories)" OK
}

